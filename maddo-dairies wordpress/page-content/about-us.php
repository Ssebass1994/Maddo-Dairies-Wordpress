<h3><strong>HISTORICAL BACKGROUND</strong></h3><br/>
<p>In 1993, Caritas MADDO initiated a 
                    dairy project by distributing heifers to three farmers through 
                    Heifer Project International (HPI), donated by Bothar-lreland. <br/>
                    The primary objective was to improve nutrition, food security, and 
                    income among the people of Masaka Diocese. Over time, the number of 
                    beneficiaries increased alongside milk production due to intensive training in sustainable
                     agriculture and livestock management.<br/><br/>
                      This progress led to the establishment of a mini dairy in 2003 with support 
                     from Heifer Project International and Bothar-lreland. This programme has distributed 
                     improved breeds of dairy cows to local families and has boosted household income for years.
                     The recently initiated "Schools Milk Programme" has also 
                     so far done a great deal in boosting the health of learners in schools that joined
                    this programme and many other schools have shown interest to join the programme
                     basing on the feedback they get from other schools that are already on the programme.</p>
